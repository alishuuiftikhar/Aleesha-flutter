-- Profiles Policies
CREATE POLICY "Public profiles are viewable by everyone." ON profiles FOR SELECT USING (true);
CREATE POLICY "Users can update own profile." ON profiles FOR UPDATE USING (auth.uid() = id);

-- Settings Policies
CREATE POLICY "Settings are viewable by everyone." ON software_house_settings FOR SELECT USING (true);
CREATE POLICY "Only admins can update settings." ON software_house_settings FOR UPDATE USING (
  EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
);

-- Seats Policies
CREATE POLICY "Seats are viewable by everyone." ON seats FOR SELECT USING (true);

-- Reservations Policies
CREATE POLICY "Users can view own reservations." ON reservations FOR SELECT USING (auth.uid() = student_id);
CREATE POLICY "Users can insert own reservations." ON reservations FOR INSERT WITH CHECK (auth.uid() = student_id);
CREATE POLICY "Admins can view all reservations." ON reservations FOR SELECT USING (
  EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
);
CREATE POLICY "Admins can update all reservations." ON reservations FOR UPDATE USING (
  EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
);

-- Fines Policies
CREATE POLICY "Users can view own fines." ON fines FOR SELECT USING (auth.uid() = student_id);
CREATE POLICY "Admins can manage all fines." ON fines FOR ALL USING (
  EXISTS (SELECT 1 FROM profiles WHERE id = auth.uid() AND role = 'admin')
);
