-- 1. PROFILES TABLE
CREATE TABLE profiles (
  id UUID REFERENCES auth.users ON DELETE CASCADE PRIMARY KEY,
  full_name TEXT,
  email TEXT UNIQUE,
  phone TEXT,
  student_id TEXT,
  course TEXT,
  profile_image TEXT,
  role TEXT DEFAULT 'student', -- 'student' or 'admin'
  status TEXT DEFAULT 'pending', -- 'pending', 'approved', 'rejected'
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. SOFTWARE HOUSE SETTINGS
CREATE TABLE software_house_settings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  house_name TEXT DEFAULT 'SeatSync',
  total_seats INT DEFAULT 30,
  reservation_deadline TIME DEFAULT '10:00:00',
  fine_amount DECIMAL DEFAULT 200,
  opening_time TIME DEFAULT '09:00:00',
  closing_time TIME DEFAULT '18:00:00',
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

